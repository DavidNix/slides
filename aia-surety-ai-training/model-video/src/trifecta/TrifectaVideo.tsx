import {Audio} from '@remotion/media';
import {AbsoluteFill, Sequence, staticFile, useVideoConfig} from 'remotion';
import {BLACK, ConvergeScene} from './ConvergeScene';
import {ClosingCard, OpeningTitle} from './Bookends';
import {T} from './timing';

export const TRIFECTA_FRAMES = T.end * 30;

export const TrifectaVideo = () => {
	const {fps} = useVideoConfig();
	return (
		<AbsoluteFill style={{backgroundColor: BLACK}}>
			{/* Generated by scripts/trifecta-sound.mjs. */}
			<Audio src={staticFile('trifecta.wav')} />
			<Sequence name="Title" durationInFrames={3.4 * fps}>
				<OpeningTitle />
			</Sequence>
			<Sequence name="Converge" from={T.converge * fps} durationInFrames={(T.closing - T.converge) * fps}>
				<ConvergeScene />
			</Sequence>
			<Sequence name="Closing" from={T.closing * fps} durationInFrames={(T.end - T.closing) * fps}>
				<ClosingCard />
			</Sequence>
		</AbsoluteFill>
	);
};
